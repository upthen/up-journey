# ---------- 创建 ----------

def test_create_minimal_trip_defaults(client):
    r = client.post(
        "/api/v1/admin/trips",
        json={
            "title": "周末杭州",
            "start_date": "2022-06-04",
            "end_date": "2022-06-05",
        },
    )
    assert r.status_code == 201, r.text
    trip = r.json()
    assert trip["status"] == "draft"  # 默认草稿
    assert trip["slug"]  # 自动生成
    assert trip["route"] == []
    assert trip["days_count"] == 2


