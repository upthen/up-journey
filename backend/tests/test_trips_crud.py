def test_admin_list_includes_drafts_and_filters(client):
    create_trip(client, title="2024 云南", start_date="2024-05-01", end_date="2024-05-07", tag_ids=[create_tag(client, "亲子")["id"]])
    create_trip(client, title="2023 青岛", start_date="2023-08-12", end_date="2023-08-15", cities=[{"city_code": CITY_CODES["青岛市"]}], status="draft")

    all_trips = client.get("/api/v1/admin/trips").json()
    assert len(all_trips) == 2  # 管理端可见草稿

    assert len(client.get("/api/v1/admin/trips", params={"status": "draft"}).json()) == 1
    assert len(client.get("/api/v1/admin/trips", params={"year": 2024}).json()) == 1
    assert len(client.get("/api/v1/admin/trips", params={"tag": "亲子"}).json()) == 1
    q = client.get("/api/v1/admin/trips", params={"q": "青岛"}).json()
    assert [t["title"] for t in q] == ["2023 青岛"]
