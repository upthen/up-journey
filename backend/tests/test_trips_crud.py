# ---------- 删除与级联 ----------

def test_delete_trip_cascades_children(client, db):
    from sqlalchemy import text

    trip = create_trip(client)
    trip_id = trip["id"]
    r = client.delete(f"/api/v1/admin/trips/{trip_id}")
    assert r.status_code == 204

    for table in ("trip_city", "trip_day", "attraction", "trip_member", "trip_tag", "trip"):
        n = db.execute(text(f"SELECT COUNT(*) FROM {table}")).scalar()
        assert n == 0, table


def test_delete_trip_404(client):
    assert client.delete("/api/v1/admin/trips/999").status_code == 404


