def test_create_with_nested_collections(client):
    dad = create_member(client, "张三", nickname="爸爸")
    son = create_member(client, "张小四", nickname="哥哥", is_child=True)
    tag1 = create_tag(client, "亲子")
    tag2 = create_tag(client, "自驾")

    trip = create_trip(client, member_ids=[dad["id"], son["id"]], tag_ids=[tag1["id"], tag2["id"]])

    assert [m["nickname"] for m in trip["members"]] == ["爸爸", "哥哥"]
    assert [t["name"] for t in trip["tags"]] == ["亲子", "自驾"]
    assert [c["display"] for c in trip["cities"]] == ["昆明", "大理", "丽江"]
    assert [c["sort_order"] for c in trip["cities"]] == [0, 1, 2]
    assert [d["day_index"] for d in trip["trip_days"]] == [1, 2]
    assert trip["trip_days"][0]["title"] == "海埂大坝喂红嘴鸥"
    assert trip["attractions"][0]["name"] == "滇池 · 海埂大坝"


