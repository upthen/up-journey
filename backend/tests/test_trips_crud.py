# ---------- 更新（整体替换嵌套集合） ----------

def test_update_replaces_nested_collections(client):
    tag = create_tag(client, "高原")
    member = create_member(client, "赵六")
    trip = create_trip(client, tag_ids=[tag["id"]])

    new_payload = trip_payload(
        title="改成青岛赶海",
        start_date="2023-08-12",
        end_date="2023-08-15",
        cities=[{"city_code": CITY_CODES["青岛市"]}],
        attractions=[{"name": "礁石滩", "city_code": CITY_CODES["青岛市"], "note": "带回一只寄居蟹。"}],
        days=[{"date": "2023-08-12", "title": "赶海"}],
        member_ids=[member["id"]],
        tag_ids=[],
    )
    r = client.put(f"/api/v1/admin/trips/{trip['id']}", json=new_payload)
    assert r.status_code == 200, r.text
    updated = r.json()

    assert updated["title"] == "改成青岛赶海"
    assert updated["tags"] == []
    assert [c["display"] for c in updated["cities"]] == ["青岛"]
    assert [a["name"] for a in updated["attractions"]] == ["礁石滩"]
    assert updated["members"][0]["name"] == "赵六"
    # slug 未提供时保持不变
    assert updated["slug"] == trip["slug"]


def test_update_can_change_slug_with_suffix_on_collision(client):
    a = create_trip(client, title="云南环线", cities=[])
    b = create_trip(client, title="另一次", cities=[])
    r = client.put(f"/api/v1/admin/trips/{b['id']}", json=trip_payload(title="另一次", slug=a["slug"], cities=[]))
    assert r.status_code == 200
    assert r.json()["slug"] == f"{a['slug']}-2"


